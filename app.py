@app.route("/generate", methods=["POST"])
def generate():
    """
    Endpoint генерации договора.

    Алгоритм:
        1. Получаем JSON из тела запроса
        2. Валидируем обязательные поля
        3. Обогащаем данные дефолтами + парсим дату договора в день/месяц/год
        4. Подставляем в шаблон
        5. Отдаём .docx файл
    """
    data = request.get_json(silent=True)

    if data is None:
        return jsonify({"ok": False, "error": "Ожидался JSON в теле запроса"}), 400

    is_valid, error = validate(data)
    if not is_valid:
        return jsonify({"ok": False, "error": error}), 400

    # Обогащаем данные: добавляем дефолты + парсим дату договора
    enriched = enrich_data(data)

    try:
        buffer = fill_template(enriched)
    except Exception as e:
        return jsonify({"ok": False, "error": f"Ошибка генерации: {str(e)}"}), 500

    return send_file(
        buffer,
        as_attachment=True,
        download_name="SLA_договор.docx",
        mimetype="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    )


