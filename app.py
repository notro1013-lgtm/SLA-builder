MAX_VALUE_LENGTH = 1000


def validate(data: dict) -> tuple[bool, str]:
    """
    Проверяет, что пришли все нужные поля и они не слишком длинные.

    Возвращает кортеж (ok, error_message):
        - (True, "")            — данные корректны
        - (False, "...")        — данные плохие, в строке причина

    type hints (dict, tuple, bool, str) — это аннотации типов. Они не
    влияют на работу кода, но помогают IDE подсказывать, что куда передавать,
    и делают код понятнее для читателя.
    """
    # data должен быть словарём (то, что пришло из JSON)
    if not isinstance(data, dict):
        return False, "Ожидался JSON-объект"

    # Проверяем каждое обязательное поле
    for field in REQUIRED_FIELDS:
        value = data.get(field, "").strip()  # .strip() убирает пробелы по краям
        if not value:
            return False, f"Не заполнено существенное условие: {field}"
        if len(value) > MAX_VALUE_LENGTH:
            return False, f"Слишком длинное значение в поле: {field}"

    # Все проверки прошли — данные годятся
    return True, ""


# ============================================================================
# БЛОК 4. ПОДСТАНОВКА В ШАБЛОН
# ============================================================================
# Алгоритм работы:
#   1. Открываем .docx-шаблон (там плейсхолдеры вроде {ИСПОЛНИТЕЛЬ_ФИО})
#   2. Проходим по всем абзацам и таблицам
#   3. Заменяем {ПЛЕЙСХОЛДЕР} на значение из формы
#   4. Сохраняем результат в память (не на диск!)
#   5. Возвращаем готовый файл пользователю
#
# Почему в память, а не на диск:
#   — быстрее (нет операций ввода-вывода)
#   — безопаснее (на диске ничего не остаётся после отправки)
#   — соответствует stateless-архитектуре


def replace_in_paragraph(paragraph, data: dict) -> None:
    """
    Заменяет плейсхолдеры в одном абзаце документа.

    Тонкий момент: в Word абзац состоит из "run-ов" — кусочков с одинаковым
    форматированием. Слово "{ИСПОЛНИТЕЛЬ_ФИО}" может быть разбито на два-три
    run-а, например: "{ИСПОЛНИТЕЛЬ" + "_" + "ФИО}". Простая замена в каждом
    run-е такое не поймает.

    Решение: собираем весь текст абзаца, делаем замену, потом перезаписываем
    первый run и очищаем остальные. Так сохраняется форматирование первого
    run-а (цвет, шрифт), а текст становится цельным.
    """
    full_text = paragraph.text
    if "{" not in full_text:
        return  # в абзаце нет плейсхолдеров — пропускаем

    # Делаем замену для каждой пары (ключ, значение) из данных формы
    new_text = full_text
    for key, value in data.items():
        placeholder = "{" + key + "}"
        new_text = new_text.replace(placeholder, str(value))

    if new_text == full_text:
        return  # после замен ничего не изменилось — выходим

    # Перезаписываем первый run, очищаем остальные.
    # Так визуальное форматирование шаблона (красный цвет плейсхолдеров)
    # автоматически сбрасывается, поскольку первый run обычно черный
    # обычный текст вокруг плейсхолдера.
    if paragraph.runs:
        paragraph.runs[0].text = new_text
        for run in paragraph.runs[1:]:
            run.text = ""


def fill_template(data: dict) -> io.BytesIO:
    """
    Открывает шаблон, подставляет данные, возвращает готовый документ в памяти.

    io.BytesIO — это "файл в оперативной памяти". Ведёт себя как обычный файл
    (умеет .read(), .write(), .seek()), но не занимает место на диске.
    """
    # Загружаем шаблон с диска (один раз на запрос).
    # Document() — конструктор из python-docx, открывает .docx как объект.
    doc = Document(TEMPLATE_PATH)

    # Проходим по всем абзацам в основной части документа
    for paragraph in doc.paragraphs:
        replace_in_paragraph(paragraph, data)

    # Проходим по таблицам (если они есть в шаблоне).
    # Таблица = строки -> ячейки -> абзацы в ячейках.
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for paragraph in cell.paragraphs:
                    replace_in_paragraph(paragraph, data)

    # Сохраняем заполненный документ в память
    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)  # перематываем "указатель чтения" в начало файла
    return buffer


def enrich_data(data: dict) -> dict:
    """
    Дополняет данные из формы дефолтными значениями и парсит дату.

    Шаблон содержит плейсхолдеры {ДД}, {ММММ}, {ГГГГ} (три отдельных),
    а пользователь вводит дату одной строкой "01 июня 2025". Разбираем
    её здесь, чтобы фронтенд не парился с этим.
    """
    # Сначала кладём дефолты — потом перезаписываем тем, что пришло из формы.
    # Это позволяет пользователю переопределить дефолт, если он добавил поле.
    result = dict(DEFAULTS)
    result.update(data)

    # Парсим дату "01 июня 2025" → ДД=01, ММММ=июня, ГГГГ=2025.
    # Если формат другой — оставляем значения "по умолчанию неизвестно",
    # пользователь поправит вручную.
    date_str = data.get("ДАТА_ДОГОВОРА", "").strip()
    parts = date_str.split()
    if len(parts) == 3:
        result["ДД"] = parts[0]
        result["ММММ"] = parts[1]
        result["ГГГГ"] = parts[2]
    else:
        result["ДД"] = "__"
        result["ММММ"] = "________"
        result["ГГГГ"] = "____"

    return result


